// Generates supabase/seed/districts_geom.sql with Perak district polygons from geoBoundaries
// (gbOpen, MYS ADM2, CC BY 4.0). Run: npm run seed:districts
//
// geoBoundaries may predate the Bagan Datuk (2016) and Muallim (2022) splits. Districts missing
// from the source keep only their centroid; the parent's polygon is used as-is.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PERAK_DISTRICTS } from '@jagasekitar/shared';

const API = 'https://www.geoboundaries.org/api/current/gbOpen/MYS/ADM2/';
const OUT = fileURLToPath(new URL('../../supabase/seed/districts_geom.sql', import.meta.url));
const USER_AGENT = process.env.NOMINATIM_USER_AGENT || 'JagaSekitar-Hackathon/1.0';

interface Feature {
  properties: Record<string, unknown>;
  geometry: { type: 'Polygon' | 'MultiPolygon'; coordinates: unknown };
}

async function getJson<T>(url: string): Promise<T> {
  const res = await fetch(url, {
    headers: { 'User-Agent': USER_AGENT },
    signal: AbortSignal.timeout(60_000),
  });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return (await res.json()) as T;
}

const normalize = (s: string) =>
  s
    .toLowerCase()
    .replace(/&/g, 'dan')
    .replace(/[^a-z]/g, '');

const meta = await getJson<{ simplifiedGeometryGeoJSON: string; boundarySource: string }>(API);
const geo = await getJson<{ features: Feature[] }>(meta.simplifiedGeometryGeoJSON);

const wanted = new Map(PERAK_DISTRICTS.map((d) => [normalize(d), d]));
// Known spelling variants in boundary datasets.
wanted.set(normalize('Larut and Matang'), 'Larut Matang dan Selama');
wanted.set(normalize('Larut Matang Selama'), 'Larut Matang dan Selama');

const lines = [
  '-- GENERATED by worker/scripts/load-districts.ts from geoBoundaries gbOpen MYS ADM2 (CC BY 4.0).',
  `-- Source: ${meta.boundarySource}. Do not edit by hand.`,
  'set search_path = public, extensions;',
];
const found = new Set<string>();
for (const f of geo.features) {
  const name = String(f.properties.shapeName ?? '');
  const district = wanted.get(normalize(name));
  if (!district || found.has(district)) continue;
  found.add(district);
  const geojson = JSON.stringify(f.geometry).replaceAll("'", "''");
  lines.push(
    `update public.districts set geom = st_multi(st_makevalid(st_setsrid(st_geomfromgeojson('${geojson}'), 4326)))::geography where state = 'PRK' and name = '${district.replaceAll("'", "''")}';`,
  );
}
writeFileSync(OUT, lines.join('\n') + '\n');

const missing = PERAK_DISTRICTS.filter((d) => !found.has(d));
console.log(`wrote ${found.size} district polygons to supabase/seed/districts_geom.sql`);
if (missing.length) console.log(`no polygon in source for: ${missing.join(', ')}`);
