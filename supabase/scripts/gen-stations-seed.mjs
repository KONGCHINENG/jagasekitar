// Generates supabase/seed/stations.sql from supabase/seed/stations_perak.csv.
// Run: node supabase/scripts/gen-stations-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../seed/', import.meta.url));
const [header, ...rows] = readFileSync(dir + 'stations_perak.csv', 'utf8')
  .trim()
  .split(/\r?\n/);
const cols = header.split(',');
const q = (s) => (s ? `'${s.replaceAll("'", "''")}'` : 'null');
const point = (r) =>
  `st_setsrid(st_makepoint(${Number(r.lon)}, ${Number(r.lat)}), 4326)::geography`;

const records = rows.map((line) => Object.fromEntries(line.split(',').map((v, i) => [cols[i], v])));
const rain = records.filter((r) => r.kind === 'rain');
const water = records.filter((r) => r.kind === 'water_level');

const out = [
  '-- GENERATED by supabase/scripts/gen-stations-seed.mjs from stations_perak.csv. Do not edit.',
  '-- SEED-* ids are placeholders until the Infobanjir adapter (Phase 3) loads real JPS station ids.',
  '-- Water-level thresholds are placeholders; the adapter and admins replace them.',
  'set search_path = public, extensions;',
  '',
  'insert into public.rain_stations (station_id, name, state, district, geom, coords_source) values',
  rain
    .map(
      (r) => `  (${q(r.station_id)}, ${q(r.name)}, 'PRK', ${q(r.district)}, ${point(r)}, 'seed')`,
    )
    .join(',\n'),
  'on conflict (station_id) do nothing;',
  '',
  'insert into public.water_level_stations',
  '  (station_id, name, river, state, district, geom, coords_source,',
  '   normal_level, alert_level, warning_level, danger_level) values',
  water
    .map(
      (r) =>
        `  (${q(r.station_id)}, ${q(r.name)}, ${q(r.river)}, 'PRK', ${q(r.district)}, ${point(r)}, 'seed', 2.0, 3.0, 3.5, 4.0)`,
    )
    .join(',\n'),
  'on conflict (station_id) do nothing;',
  '',
];
writeFileSync(dir + 'stations.sql', out.join('\n'));
console.log(`wrote ${rain.length} rain + ${water.length} water-level stations`);
